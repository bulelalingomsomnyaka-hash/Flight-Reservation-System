    //Flight numbers for international and domestic
    private boolean syncFlight() {
        String type = String.valueOf(typeBox.getSelectedItem());
        if (type.equals("International Flight")) {
            flightNo = "FA-202";
            
        } else if (type.equals("Domestic Flight")) {
            flightNo = "FA-901";
        } else {
            flightNo = "";
            return false;
        }
        seatsLeft = getSeats(flightNo).size();
        return true;
    }
    //Payment method for each source to destination prices
    private boolean payment(){
        
        int ticketPrice = 0;
        String p = String.valueOf(typeBox.getSelectedItem());
        String f = String.valueOf(fromBox.getSelectedItem());
        String t = String.valueOf(toBox.getSelectedItem());
        if(p.equals("International Flight")){
            if(f.equals("Cape Town") && t.equals("London")){
               ticketPrice = 8172;
            }else if (f.equals("Cape Town") && t.equals("Dubai")) {
            ticketPrice = 9800; 
            }else if (f.equals("Johannesburg") && t.equals("London")){
                ticketPrice = 8192;
            }else if(f.equals("Johannesburg") && t.equals("Dubai")){
                ticketPrice = 8600;
            }
        }else if (p.equals("Domestic Flight")){
            if(f.equals("Cape Town") && t.equals("Durban")){
                ticketPrice = 1500;
            }else if(f.equals("Cape Town") && t.equals("Umtata")){
                ticketPrice = 3800;
            }else if(f.equals("Johannesburg") && t.equals("Durban")){
                ticketPrice = 900;
            }else if(f.equals("Johannesburg") && t.equals("Umtata")){
                ticketPrice = 2400;
            }
        }
        if(ticketPrice == 0){
            JOptionPane.showMessageDialog(this,"No price found for " + f + " to " + t);
            return false;
        }
       lastPrice = ticketPrice;
        int choice = JOptionPane.showConfirmDialog(this,"\n"+p+
                " \nYour ticket price from " + f + " to " + t + " Is R " + ticketPrice +
                "\nDo You want to Continue?", "Ticket Price", JOptionPane.YES_NO_OPTION);
        
        return choice == JOptionPane.YES_OPTION;
        
}
//control statement of flight type if it is changed and syncig them
    private void onTypeChanged() {
        if (syncFlight()) {
            statusLabel.setText("Status: " + typeBox.getSelectedItem() + " (" + flightNo + ") - "
                    + seatsLeft + " seats left");
        } else {
            statusLabel.setText("Status: Please select a flight type.");
        }
    }
//Checking availablity of seats
    private void onCheckSeats() {
        if (!syncFlight()) {
            JOptionPane.showMessageDialog(this, "Select Flight First!");
        } else if (seatsLeft > 0) {
            JOptionPane.showMessageDialog(this, seatsLeft + " Seats Available on " + flightNo);
            statusLabel.setText("Status: " + seatsLeft + " seats available on " + flightNo);
        } else {
            JOptionPane.showMessageDialog(this, "Flight is Full!");
            statusLabel.setText("Status: " + flightNo + " is full.");
        }
    }
