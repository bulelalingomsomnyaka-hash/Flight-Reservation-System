    private void onBookTicket() {
       
          Date selectedDate = jDateChooser1.getDate();
        if(selectedDate == null){
            JOptionPane.showMessageDialog(this, "Please select Date!");
            return;
        }
        String dateString = new SimpleDateFormat("dd-MM-yyyy").format(selectedDate);
        
        if (!syncFlight()) {
            JOptionPane.showMessageDialog(this, "Select Flight First!");
            return;
        }
        String name = nameField.getText().trim();
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter your name please");
            nameField.requestFocus();
            return;
        }
        String from = String.valueOf(fromBox.getSelectedItem()).trim();
        String to = String.valueOf(toBox.getSelectedItem()).trim();
        if (from.isEmpty() || to.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select where you are flying from and to.");
            return;
        }
        boolean international = typeBox.getSelectedItem().equals("International Flight");
        boolean toIsInternational = to.equals("London") || to.equals("Dubai");
        if (international != toIsInternational) {
            JOptionPane.showMessageDialog(this, international
                    ? "International flights go to London or Dubai."
                    : "Domestic flights go to Durban or Umtata.");
            return;
        }
        ArrayList<String> seats = getSeats(flightNo);
        if (seats.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Flight is Full!");
            statusLabel.setText("Status: " + flightNo + " is full.");
            return;
        }
       if(!payment()){
           statusLabel.setText("Status: Booking cancelle at price confirmation.");//**
           return;
       }

        SeatSelection dialog = new SeatSelection(this, flightNo, name, seats);
        dialog.setVisible(true);                  // waits here until it is closed
        String seat = dialog.getBookedSeat();
        seatsLeft = seats.size();

        if (seat == null) {
            statusLabel.setText("Status: Booking cancelled - no seat chosen.");
            return;
        }
         payment();
        timeFlight();
        gateFlight();
       if (!BookingDAO.saveBooking(loggedInUser, name, flightNo, from, to, seat, lastPrice,
            dateString, String.valueOf(Dtime), String.valueOf(Atime), String.valueOf(gate))) {
        seats.add(seat);
        seatsLeft = seats.size();
        JOptionPane.showMessageDialog(this,
                "Could not save the booking. Check that MySQL is running.");
        return;
    }

String ticket = BookingDAO.buildTicket(name, flightNo, from, to, seat, dateString,
            String.valueOf(Dtime), String.valueOf(Atime), String.valueOf(gate));
    myDataBase.add(ticket);
    statusLabel.setText("Status: Booked " + seat + " on " + flightNo + " - " + seatsLeft + " seats left");
    JOptionPane.showMessageDialog(this, "Booking confirmed!\n\n" + ticket,
            "Bookings", JOptionPane.INFORMATION_MESSAGE);
        
       
    }

  private void onViewBookings() {
    ArrayList<String> bookings = BookingDAO.getBookingsForUser(loggedInUser);
    if (bookings.isEmpty()) {
        JOptionPane.showMessageDialog(this, "You have no bookings yet.");
        return;
    }
    StringBuilder sb = new StringBuilder();
    int n = 1;
    for (String ticket : bookings) {
        sb.append("Ticket ").append(n++).append("\n")
          .append(ticket).append("\n")
          .append("--------------------------------------\n");
    }
    JTextArea area = new JTextArea(sb.toString(), 16, 40);
    area.setEditable(false);
    JOptionPane.showMessageDialog(this, new JScrollPane(area),
            "Ticket, KINDLY SCREENSHOT & PRINT IT FOR WHEN YOU ARE BOARDING (" + bookings.size() + ")",
            JOptionPane.INFORMATION_MESSAGE);
}
