    private void loginBtn2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginBtn2ActionPerformed
        // TODO add your handling code here:
        // ADDED: both boxes must be filled in, then open the booking screen
        String name = jTextField1.getText().trim();
        String password = jPasswordField1.getText().trim();
        if (name.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter your name and password.");
            return;
        }
         if (!BookingDAO.validateLogin(name, password)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Wrong name or password.");
        jPasswordField1.setText("");
        return;
    }

        Flight flight = new Flight();
        flight.setPassengerName(name);
        flight.setVisible(true);
        dispose();
    }//GEN-LAST:event_loginBtn2ActionPerformed

